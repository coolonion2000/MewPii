export type I18nKey = keyof (typeof dict)['zh'];

let current: Lang = (() => {
  const saved = localStorage.getItem('pii-lang');
  if (saved === 'zh' || saved === 'en') return saved;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
})();

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  localStorage.setItem('pii-lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  for (const fn of listeners) fn();
}

export function onLangChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key: I18nKey, params?: Record<string, string>): string {
  let out = (dict[current][key] ?? dict.en[key] ?? key) as string;
  if (params) {
    for (const [k, v] of Object.entries(params)) out = out.replace(`{${k}}`, v);
  }
  return out;
}
