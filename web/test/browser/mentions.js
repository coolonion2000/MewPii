async (page) => {
  page.setDefaultTimeout(8000);
  const check = (value, message) => { if (!value) throw Error(message); };
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto('http://127.0.0.1:31049/test/browser/fixture.html?mentions=1');
  const input = page.getByRole('textbox');
  await input.fill('a@example.com');
  check(await page.getByRole('listbox').count() === 0, 'email triggered mentions');
  await input.fill('看看 @cmps');
  await page.getByRole('option', { name: /Composer.tsx/ }).waitFor();
  await input.evaluate(node => node.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })));
  check(await page.getByRole('listbox').count() === 0, 'IME did not hide suggestions');
  await input.press('Enter');
  check(await page.evaluate(() => window.fixture.sent.length) === 0, 'IME confirmation submitted the prompt');
  await input.evaluate(node => node.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })));
  await input.fill('看看 @cmps');
  await page.getByRole('option', { name: /Composer.tsx/ }).waitFor();
  await input.press('Enter');
  check(await input.inputValue() === '看看 ', 'selection did not replace the query');
  check(await page.locator('.composer .file-mention-chip').count() === 1, 'selected chip missing');
  await input.fill('看看 @src');
  await page.getByRole('option', { name: /src/ }).click();
  check(await page.locator('.composer .file-mention-chip').count() === 2, 'directory chip missing');
  await page.locator('.composer .file-mention-chip').first().getByRole('button').first().click();
  await page.locator('.composer .file-mention-detail').getByText('/fixture/src/Composer.tsx', { exact: true }).waitFor();
  await page.getByRole('button', { name: '预览文件', exact: true }).click();
  await page.getByText('fixture file preview', { exact: true }).waitFor();
  await page.evaluate(() => window.fixture.switchSession());
  await page.waitForFunction(() => document.title.endsWith('small'));
  check(await page.locator('.composer .file-mention-chip').count() === 0, 'references leaked into other session');
  await page.evaluate(() => window.fixture.switchSession());
  await page.waitForFunction(() => document.querySelectorAll('.composer .file-mention-chip').length === 2);
  await page.evaluate(() => window.fixture.failNext = true);
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.composer .file-mention-chip').length === 2 && window.fixture.sent.length === 1);
  check(await input.inputValue() === '看看', 'failed send lost text');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.composer .file-mention-chip').length === 0 && window.fixture.sent.length === 2);
  const message = await page.evaluate(() => window.fixture.sent[1].message);
  check(message.includes('/fixture/src/Composer.tsx') && message.includes('"isDir":true'), 'sent message omitted references');
  check(!message.includes('fixture file preview'), 'file content was injected');
  check(await page.locator('.msg-user .file-mention-chip').count() >= 2, 'sent references are not rendered as chips');
  const requests = await page.evaluate(() => window.fixture.requests.filter(url => url.includes('mode=mention')));
  check(requests.length > 0 && requests.every(url => /[?&]agent=fixture(?:&|$)/.test(url)), 'search lost agent identity');

  await input.fill('@slow');
  await page.waitForFunction(() => window.fixture.requests.some(url => url.includes('q=slow')));
  await input.fill('@cmps');
  await page.getByRole('option', { name: /Composer.tsx/ }).waitFor();
  await page.waitForTimeout(800);
  check(await page.getByRole('option', { name: /Stale/ }).count() === 0, 'stale response replaced new results');
  await input.press('Escape');
  check(await page.getByRole('listbox').count() === 0, 'Escape did not dismiss');
  check(await input.inputValue() === '@cmps', 'Escape changed plain text');
  await input.fill('@none');
  await page.getByText('没有匹配的文件或目录', { exact: true }).waitFor();
  await input.press('Escape');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  check(await page.evaluate(() => window.fixture.sent.at(-1).message) === '@none', 'unselected @ query was not plain text');

  await page.setViewportSize({ width: 390, height: 844 });
  await input.fill('@cmps');
  await page.getByRole('option', { name: /Composer.tsx/ }).waitFor();
  await page.evaluate(() => { Object.defineProperty(visualViewport, 'height', { configurable: true, value: 420 }); visualViewport.dispatchEvent(new Event('resize')); });
  await page.waitForFunction(() => document.documentElement.style.getPropertyValue('--mobile-viewport-height') === '420px');
  const menu = await page.getByRole('listbox').boundingBox();
  check(menu && menu.y >= 0 && menu.y + menu.height <= 420, 'mobile mention menu hidden by keyboard');
  await page.getByRole('option', { name: /Composer.tsx/ }).click();
  await page.getByRole('button', { name: '移除引用: /fixture/src/Composer.tsx', exact: true }).click();
  check(await page.locator('.composer .file-mention-chip').count() === 0, 'mobile remove failed');
  return 'PASS: keyboard/file/folder selection, preview, draft isolation, send/failure recovery, remote routing, stale response, Escape/plain text, phone keyboard and removal';
}
